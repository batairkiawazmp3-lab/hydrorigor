#!/usr/bin/env node
// Builds the Search Console trend from docs/research/search-console/log.md:
//   - a "Trend" section in latest.md (between <!-- trend:start --> and <!-- trend:end -->)
//     with up/down arrows against the previous check, the same weekday last week and the baseline;
//   - docs/research/search-console/trend.svg, two stacked charts (impressions per data day and
//     average position) so the direction of traffic is visible at a glance.
// Usage: node scripts/search-console-trend.mjs            (write both files)
//        node scripts/search-console-trend.mjs --summary  (print a one-line summary only)
// Arrows mean better or worse, not bigger or smaller: ▲ better, ▼ worse, ▬ no change.
// For average position a lower number is better, so a rise in position shows ▼.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'docs/research/search-console');
const logPath = join(dir, 'log.md');
const latestPath = join(dir, 'latest.md');
const svgPath = join(dir, 'trend.svg');

const MONTHS = { Jan: 0, Feb: 1, Mar: 2, Apr: 3, May: 4, Jun: 5, Jul: 6, Aug: 7, Sep: 8, Oct: 9, Nov: 10, Dec: 11 };
const DAY = 86400000;

export function parseLog(text) {
  const rows = [];
  for (const line of text.split('\n')) {
    if (!/^\| 20\d\d-\d\d-\d\d/.test(line)) continue;
    const cells = line.replace(/^\||\|$/g, '').split('|').map((c) => c.trim());
    if (cells.length < 6) continue;
    const date = cells[0].slice(0, 10);
    // The checks table comes first; "Changes to watch" rows have a route in cell 2.
    if (!/^\d+$/.test(cells[1])) continue;
    const range = /([A-Z][a-z]{2}) (\d+)–(?:([A-Z][a-z]{2}) )?(\d+)/.exec(cells[0]);
    let start = null;
    let end = null;
    if (range) {
      const year = Number(date.slice(0, 4));
      start = Date.UTC(year, MONTHS[range[1]], Number(range[2]));
      end = Date.UTC(year, MONTHS[range[3] ?? range[1]], Number(range[4]));
    }
    const days = start === null ? null : Math.round((end - start) / DAY) + 1;
    rows.push({
      date,
      end: end === null ? null : new Date(end).toISOString().slice(0, 10),
      days,
      clicks: Number(cells[1]),
      impressions: Number(cells[2]),
      ctr: Number(cells[3].replace('%', '')),
      position: Number(cells[4]),
      queries: Number.parseInt(cells[5], 10),
      pages: Number.parseInt(cells[6], 10),
    });
  }
  return rows.sort((a, b) => a.date.localeCompare(b.date));
}

const round = (n, d = 1) => Math.round(n * 10 ** d) / 10 ** d;
const signed = (n, d = 0) => {
  const r = round(n, d);
  return `${r > 0 ? '+' : r < 0 ? '−' : '±'}${Math.abs(r).toFixed(d)}`;
};
// higherIsBetter: true for clicks, impressions, CTR, queries; false for position.
function arrow(delta, higherIsBetter, d = 0) {
  const r = round(delta, d);
  if (r === 0) return '▬';
  return (r > 0) === higherIsBetter ? '▲' : '▼';
}
function change(cur, prev, key, { d = 0, better = true, unit = '', pct = false } = {}) {
  if (!prev) return '—';
  const delta = cur[key] - prev[key];
  let text = `${arrow(delta, better, d)} ${signed(delta, d)}${unit}`;
  if (pct && prev[key] > 0 && round(delta, d) !== 0) text += ` (${signed((delta / prev[key]) * 100)}%)`;
  return text;
}
const perDay = (r) => (r.days ? round(r.impressions / r.days, 1) : null);

function compareLine(label, cur, other) {
  if (!other) return `- **${label}:** no check on that date.`;
  return (
    `- **${label}** (${other.date}, data to ${other.end ?? '?'}): ` +
    `impressions ${other.impressions} → ${cur.impressions} ${change(cur, other, 'impressions', { pct: true })}, ` +
    `clicks ${other.clicks} → ${cur.clicks} ${change(cur, other, 'clicks')}, ` +
    `CTR ${other.ctr}% → ${cur.ctr}% ${change(cur, other, 'ctr', { d: 1, unit: ' pt' })}, ` +
    `position ${other.position} → ${cur.position} ${change(cur, other, 'position', { d: 1, better: false })}, ` +
    `impressions per data day ${perDay(other)} → ${perDay(cur)}.`
  );
}

export function buildTrend(rows) {
  const cur = rows.at(-1);
  const prev = rows.at(-2);
  const weekAgo = new Date(Date.parse(cur.date) - 7 * DAY).toISOString().slice(0, 10);
  const lastWeek = rows.find((r) => r.date === weekAgo);
  const base = rows[0];
  const lines = [
    '<!-- trend:start -->',
    '## Trend',
    '',
    'Generated by `node scripts/search-console-trend.mjs` from `log.md`. ▲ better, ▼ worse, ▬ no change',
    '(for average position a lower number is better). While the site is younger than 28 days the window',
    'keeps growing, so totals rise on their own; impressions per data day is the fairer rate to compare.',
    '',
    compareLine('Since the previous check', cur, prev),
    compareLine('Since the same weekday last week', cur, lastWeek),
    compareLine('Since the baseline', cur, base),
    '',
    '![Two line charts of Search Console checks: impressions per data day, and average position where lower is better](trend.svg)',
    '',
    '| Checked | Data to | Impressions | Change | Per day | Clicks | Change | CTR | Position | Change | Queries |',
    '| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |',
  ];
  const desc = [...rows].reverse();
  desc.forEach((r, i) => {
    const p = desc[i + 1];
    lines.push(
      `| ${r.date} | ${r.end ?? '?'} | ${r.impressions} | ${change(r, p, 'impressions', { pct: true })} | ${perDay(r) ?? '?'} | ` +
        `${r.clicks} | ${change(r, p, 'clicks')} | ${r.ctr}% | ${r.position} | ${change(r, p, 'position', { d: 1, better: false })} | ${r.queries} |`,
    );
  });
  lines.push('<!-- trend:end -->');
  return lines.join('\n');
}

export function summary(rows) {
  const cur = rows.at(-1);
  const prev = rows.at(-2);
  return (
    `${cur.clicks} clicks ${change(cur, prev, 'clicks')}, ${cur.impressions} impressions ${change(cur, prev, 'impressions', { pct: true })}, ` +
    `CTR ${cur.ctr}% ${change(cur, prev, 'ctr', { d: 1, unit: ' pt' })}, position ${cur.position} ${change(cur, prev, 'position', { d: 1, better: false })}`
  );
}

// ---- SVG: two stacked panels sharing the x axis (no dual axis), phone-friendly viewBox.
function panel({ rows, value, title, y0, invert, fmt }) {
  const W = 720;
  const left = 70;
  const right = 40;
  const top = y0 + 56;
  const h = 200;
  const vals = rows.map(value);
  // Round the axis out to tidy steps of 10 so the gridlines read cleanly.
  const lo = Math.max(0, Math.floor(Math.min(...vals) / 10) * 10);
  let hi = Math.ceil(Math.max(...vals) / 10) * 10;
  if ((hi - lo) % 20) hi += 10;
  if (hi === lo) hi = lo + 20;
  // Time scale: points sit at their real data dates, not evenly spaced.
  const t0 = Date.parse(rows[0].end);
  const span = Date.parse(rows.at(-1).end) - t0 || 1;
  const x = (i) => left + ((Date.parse(rows[i].end) - t0) / span) * (W - left - right);
  const y = (v) => (invert ? top + ((v - lo) / (hi - lo)) * h : top + h - ((v - lo) / (hi - lo)) * h);
  const out = [`<text x="${left}" y="${y0 + 32}" class="title">${title}</text>`];
  for (let k = 0; k <= 2; k += 1) {
    const v = lo + ((hi - lo) * k) / 2;
    out.push(`<line x1="${left}" x2="${W - right}" y1="${round(y(v))}" y2="${round(y(v))}" class="grid"/>`);
    out.push(`<text x="${left - 10}" y="${round(y(v)) + 7}" text-anchor="end" class="axis">${fmt(v)}</text>`);
  }
  const pts = rows.map((r, i) => `${round(x(i))},${round(y(value(r)))}`).join(' ');
  out.push(`<polyline points="${pts}" class="line"/>`);
  rows.forEach((r, i) => {
    out.push(`<circle cx="${round(x(i))}" cy="${round(y(value(r)))}" r="5" class="dot"><title>${r.date}: ${fmt(value(r))}</title></circle>`);
  });
  const last = rows.length - 1;
  out.push(
    `<text x="${round(x(last))}" y="${round(y(value(rows[last]))) - 14}" text-anchor="end" class="label">${fmt(value(rows[last]))}</text>`,
  );
  return { svg: out.join('\n'), x, bottom: top + h };
}

export function buildSvg(rows) {
  const data = rows.filter((r) => r.days);
  const a = panel({ rows: data, value: perDay, title: 'Impressions per data day (up is better)', y0: 0, invert: false, fmt: (v) => round(v, 1).toFixed(1).replace(/\.0$/, '') });
  const b = panel({ rows: data, value: (r) => r.position, title: 'Average position (axis flipped: up is better)', y0: 290, invert: true, fmt: (v) => round(v, 1).toFixed(1).replace(/\.0$/, '') });
  const ticks = data
    .map((r, i) => ({ r, i }))
    .filter(({ r, i }) => i === 0 || i === data.length - 1 || (Date.parse(r.end) - Date.parse(data[0].end)) % (4 * DAY) === 0)
    .map(({ r, i }) => `<text x="${round(b.x(i))}" y="${b.bottom + 34}" text-anchor="middle" class="axis">${r.end.slice(5)}</text>`)
    .join('\n');
  const H = b.bottom + 60;
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 720 ${H}" role="img" aria-label="Search Console trend: impressions per data day and average position by check">
<style>
.bg{fill:#fcfcfb}.title{font:600 24px system-ui,sans-serif;fill:#0b0b0b}.axis,.label{font:20px system-ui,sans-serif;fill:#52514e}.label{fill:#0b0b0b;font-weight:600}
.grid{stroke:#e4e3df;stroke-width:1}.line{fill:none;stroke:#2a78d6;stroke-width:2;stroke-linejoin:round}.dot{fill:#2a78d6;stroke:#fcfcfb;stroke-width:2}
@media (prefers-color-scheme: dark){.bg{fill:#1a1a19}.title,.label{fill:#f0efec}.axis{fill:#c3c2b7}.grid{stroke:#383835}.line{stroke:#3987e5}.dot{fill:#3987e5;stroke:#1a1a19}}
</style>
<rect class="bg" width="720" height="${H}"/>
${a.svg}
${b.svg}
${ticks}
<text x="360" y="${H - 4}" text-anchor="middle" class="axis">last data day of each check</text>
</svg>
`;
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  const rows = parseLog(readFileSync(logPath, 'utf8'));
  if (rows.length < 2) throw new Error('log.md needs at least two checks');
  if (process.argv.includes('--summary')) {
    console.log(summary(rows));
  } else {
    const trend = buildTrend(rows);
    let latest = readFileSync(latestPath, 'utf8');
    if (latest.includes('<!-- trend:start -->')) {
      latest = latest.replace(/<!-- trend:start -->[\s\S]*?<!-- trend:end -->/, trend);
    } else {
      latest = latest.replace(/\n## Queries/, `\n${trend}\n\n## Queries`);
    }
    writeFileSync(latestPath, latest);
    writeFileSync(svgPath, buildSvg(rows));
    console.log(summary(rows));
  }
}
